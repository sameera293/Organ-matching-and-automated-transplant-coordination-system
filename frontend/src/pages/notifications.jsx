import React, { useEffect, useState } from "react";
import {
  Bell,
  Check,
  CheckCheck,
  RefreshCw,
  AlertTriangle,
  Info,
  AlertCircle,
  Clock,
} from "lucide-react";

import { api } from "../services/api";

export default function Notifications() {
  const [notifications, setNotifications] = useState([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState("");
  const [statusFilter, setStatusFilter] = useState("");
  const [severityFilter, setSeverityFilter] = useState("");

  const loadNotifications = async () => {
    try {
      setLoading(true);
      setError("");

      const params = {};

      if (statusFilter) {
        params.status = statusFilter;
      }

      if (severityFilter) {
        params.severity = severityFilter;
      }

      const data = await api.getNotifications(params);
      setNotifications(Array.isArray(data) ? data : []);
    } catch (err) {
      console.error("Failed to load notifications:", err);
      setError(err.message || "Failed to load notifications.");
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    loadNotifications();
  }, [statusFilter, severityFilter]);

  const markAsRead = async (notificationId) => {
    try {
      await api.markNotificationRead(notificationId);
      await loadNotifications();
    } catch (err) {
      setError(err.message || "Failed to mark notification as read.");
    }
  };

  const markAllAsRead = async () => {
    try {
      await api.markAllNotificationsRead();
      await loadNotifications();
    } catch (err) {
      setError(err.message || "Failed to mark notifications as read.");
    }
  };

  const getSeverityIcon = (severity) => {
    switch ((severity || "").toUpperCase()) {
      case "CRITICAL":
        return <AlertCircle size={22} />;

      case "WARNING":
        return <AlertTriangle size={22} />;

      default:
        return <Info size={22} />;
    }
  };

  const getSeverityClass = (severity) => {
    switch ((severity || "").toUpperCase()) {
      case "CRITICAL":
        return "badge-danger";

      case "WARNING":
        return "badge-warning";

      default:
        return "badge-info";
    }
  };

  const formatType = (type) => {
    if (!type) return "Notification";

    return type
      .replaceAll("_", " ")
      .toLowerCase()
      .replace(/\b\w/g, (letter) => letter.toUpperCase());
  };

  const formatDate = (date) => {
    if (!date) return "-";

    const parsed = new Date(date);

    if (Number.isNaN(parsed.getTime())) {
      return date;
    }

    return parsed.toLocaleString();
  };

  const unreadCount = notifications.filter(
    (item) => item.status === "UNREAD"
  ).length;

  return (
    <div>
      {/* PAGE HEADER */}
      <div className="page-header">
        <div>
          <h1 className="page-title">Notifications</h1>

          <p className="page-subtitle">
            Alerts and system events generated by the organ matching
            decision-support system.
          </p>
        </div>

        <div style={{ display: "flex", gap: "10px" }}>
          <button
            className="btn btn-secondary"
            onClick={loadNotifications}
            disabled={loading}
          >
            <RefreshCw size={16} />
            Refresh
          </button>

          <button
            className="btn btn-primary"
            onClick={markAllAsRead}
            disabled={unreadCount === 0}
          >
            <CheckCheck size={16} />
            Mark All as Read
          </button>
        </div>
      </div>

      {/* SUMMARY */}
      <div className="stat-grid">
        <div className="stat-card">
          <div
            className="stat-icon"
            style={{
              backgroundColor: "#e0f2fe",
              color: "#0284c7",
            }}
          >
            <Bell size={22} />
          </div>

          <div>
            <div className="stat-value">{notifications.length}</div>
            <div className="stat-label">Notifications</div>
          </div>
        </div>

        <div className="stat-card">
          <div
            className="stat-icon"
            style={{
              backgroundColor: "#fef3c7",
              color: "#d97706",
            }}
          >
            <Clock size={22} />
          </div>

          <div>
            <div className="stat-value">{unreadCount}</div>
            <div className="stat-label">Unread</div>
          </div>
        </div>

        <div className="stat-card">
          <div
            className="stat-icon"
            style={{
              backgroundColor: "#fee2e2",
              color: "#dc2626",
            }}
          >
            <AlertCircle size={22} />
          </div>

          <div>
            <div className="stat-value">
              {
                notifications.filter(
                  (item) => item.severity === "CRITICAL"
                ).length
              }
            </div>
            <div className="stat-label">Critical</div>
          </div>
        </div>

        <div className="stat-card">
          <div
            className="stat-icon"
            style={{
              backgroundColor: "#fef3c7",
              color: "#d97706",
            }}
          >
            <AlertTriangle size={22} />
          </div>

          <div>
            <div className="stat-value">
              {
                notifications.filter(
                  (item) => item.severity === "WARNING"
                ).length
              }
            </div>
            <div className="stat-label">Warnings</div>
          </div>
        </div>
      </div>

      {/* FILTERS */}
      <div className="card" style={{ marginTop: "20px" }}>
        <div
          style={{
            display: "flex",
            gap: "16px",
            alignItems: "center",
            flexWrap: "wrap",
          }}
        >
          <div>
            <label className="form-label">Status</label>

            <select
              className="form-control"
              value={statusFilter}
              onChange={(e) => setStatusFilter(e.target.value)}
            >
              <option value="">All Status</option>
              <option value="UNREAD">Unread</option>
              <option value="READ">Read</option>
            </select>
          </div>

          <div>
            <label className="form-label">Severity</label>

            <select
              className="form-control"
              value={severityFilter}
              onChange={(e) => setSeverityFilter(e.target.value)}
            >
              <option value="">All Severity</option>
              <option value="INFO">Info</option>
              <option value="WARNING">Warning</option>
              <option value="CRITICAL">Critical</option>
            </select>
          </div>
        </div>
      </div>

      {/* ERROR */}
      {error && (
        <div
          className="card"
          style={{
            marginTop: "20px",
            borderColor: "var(--danger)",
            backgroundColor: "var(--danger-bg)",
          }}
        >
          <div
            style={{
              display: "flex",
              alignItems: "center",
              gap: "10px",
              color: "var(--danger)",
            }}
          >
            <AlertTriangle size={22} />
            <strong>{error}</strong>
          </div>
        </div>
      )}

      {/* NOTIFICATION LIST */}
      <div className="card" style={{ marginTop: "20px" }}>
        <div className="card-header">
          <div>
            <h2 className="card-title">Notification Center</h2>

            <p
              style={{
                margin: "4px 0 0",
                color: "var(--text-secondary)",
              }}
            >
              System-generated alerts for matching, organ preservation,
              logistics and other events.
            </p>
          </div>
        </div>

        {loading ? (
          <div
            style={{
              textAlign: "center",
              padding: "50px 20px",
              color: "var(--text-secondary)",
            }}
          >
            <RefreshCw
              size={32}
              className="animate-spin"
              style={{ marginBottom: "12px" }}
            />

            <p>Loading notifications...</p>
          </div>
        ) : notifications.length === 0 ? (
          <div
            style={{
              textAlign: "center",
              padding: "60px 20px",
              color: "var(--text-secondary)",
            }}
          >
            <Bell
              size={42}
              style={{
                marginBottom: "12px",
                opacity: 0.5,
              }}
            />

            <h3 style={{ margin: "0 0 8px" }}>
              No Notifications
            </h3>

            <p style={{ margin: 0 }}>
              There are no notifications matching the selected filters.
            </p>
          </div>
        ) : (
          <div style={{ display: "flex", flexDirection: "column", gap: "12px" }}>
            {notifications.map((notification) => {
              const isUnread = notification.status === "UNREAD";

              return (
                <div
                  key={notification.notification_id}
                  style={{
                    border: "1px solid var(--border-color)",
                    borderRadius: "12px",
                    padding: "18px",
                    backgroundColor: isUnread
                      ? "var(--bg-subtle)"
                      : "var(--bg-card)",
                    boxShadow: isUnread
                      ? "0 2px 8px rgba(0,0,0,0.04)"
                      : "none",
                  }}
                >
                  <div
                    style={{
                      display: "flex",
                      justifyContent: "space-between",
                      gap: "20px",
                      alignItems: "flex-start",
                    }}
                  >
                    {/* LEFT */}
                    <div
                      style={{
                        display: "flex",
                        gap: "14px",
                        flex: 1,
                      }}
                    >
                      <div
                        style={{
                          minWidth: "42px",
                          height: "42px",
                          borderRadius: "10px",
                          display: "flex",
                          alignItems: "center",
                          justifyContent: "center",
                          backgroundColor:
                            notification.severity === "CRITICAL"
                              ? "#fee2e2"
                              : notification.severity === "WARNING"
                              ? "#fef3c7"
                              : "#e0f2fe",
                          color:
                            notification.severity === "CRITICAL"
                              ? "#dc2626"
                              : notification.severity === "WARNING"
                              ? "#d97706"
                              : "#0284c7",
                        }}
                      >
                        {getSeverityIcon(notification.severity)}
                      </div>

                      <div style={{ flex: 1 }}>
                        <div
                          style={{
                            display: "flex",
                            alignItems: "center",
                            gap: "8px",
                            flexWrap: "wrap",
                            marginBottom: "6px",
                          }}
                        >
                          <strong>
                            {formatType(notification.type)}
                          </strong>

                          <span
                            className={`badge ${getSeverityClass(
                              notification.severity
                            )}`}
                          >
                            {notification.severity}
                          </span>

                          <span
                            className={`badge ${
                              isUnread
                                ? "badge-warning"
                                : "badge-secondary"
                            }`}
                          >
                            {notification.status}
                          </span>
                        </div>

                        <p
                          style={{
                            margin: "0 0 8px",
                            color: "var(--text-primary)",
                            lineHeight: 1.5,
                          }}
                        >
                          {notification.message}
                        </p>

                        <div
                          style={{
                            fontSize: "0.85rem",
                            color: "var(--text-secondary)",
                          }}
                        >
                          {notification.notification_id}
                          {" • "}
                          {formatDate(notification.created_at)}
                        </div>
                      </div>
                    </div>

                    {/* ACTION */}
                    {isUnread && (
                      <button
                        className="btn btn-outline btn-sm"
                        onClick={() =>
                          markAsRead(notification.notification_id)
                        }
                      >
                        <Check size={15} />
                        Mark as Read
                      </button>
                    )}
                  </div>
                </div>
              );
            })}
          </div>
        )}
      </div>

      {/* SAFETY NOTE */}
      <div
        className="card"
        style={{
          marginTop: "20px",
          borderLeft: "4px solid var(--primary)",
        }}
      >
        <div
          style={{
            display: "flex",
            gap: "12px",
            alignItems: "flex-start",
          }}
        >
          <Info size={22} color="var(--primary)" />

          <div>
            <h3 style={{ margin: "0 0 6px" }}>
              Decision-Support Notice
            </h3>

            <p
              style={{
                margin: 0,
                color: "var(--text-secondary)",
                lineHeight: 1.5,
              }}
            >
              Notifications are generated to support research-oriented
              monitoring of organ matching, preservation and logistics
              events. They do not authorize medical allocation decisions.
            </p>
          </div>
        </div>
      </div>
    </div>
  );
}